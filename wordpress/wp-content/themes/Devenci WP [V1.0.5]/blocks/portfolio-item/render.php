<?php
// Portfolio item render callback

$category = isset( $attributes['category'] ) ? trim( (string) $attributes['category'] ) : '';
$image_id = isset( $attributes['imageId'] ) ? (int) $attributes['imageId'] : 0;
$alt      = isset( $attributes['imageAlt'] ) ? $attributes['imageAlt'] : '';
$link     = isset( $attributes['link'] ) ? $attributes['link'] : '';

$image = devenci_attachment_image( $image_id, 'large', 'portfolio-img', $alt );

if ( ! $image ) {
	$image = '<div class="portfolio-img-placeholder">' . esc_html__( 'Select a portfolio image', 'devenci' ) . '</div>';
}
?>
<div class="portfolio-item" data-category="<?php echo esc_attr( sanitize_title( $category ) ); ?>">
	<?php echo $image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
	<div class="portfolio-overlay">
		<?php echo $content; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Rendered inner blocks. ?>
		<?php if ( $link ) : ?>
			<a href="<?php echo esc_url( $link ); ?>" class="portfolio-link" target="_blank" rel="noopener noreferrer" aria-label="<?php esc_attr_e( 'Open project link', 'devenci' ); ?>">
				<i class="fas fa-link" aria-hidden="true"></i>
			</a>
		<?php endif; ?>
	</div>
</div>
