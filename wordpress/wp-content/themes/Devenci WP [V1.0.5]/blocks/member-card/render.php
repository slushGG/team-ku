<?php
// Member card render callback

$url      = isset( $attributes['url'] ) ? $attributes['url'] : '';
$image_id = isset( $attributes['imageId'] ) ? (int) $attributes['imageId'] : 0;
$alt      = isset( $attributes['imageAlt'] ) ? $attributes['imageAlt'] : '';
$delay    = isset( $attributes['delay'] ) ? $attributes['delay'] : '0s';

$image = devenci_attachment_image( $image_id, 'full', 'member-img', $alt );

if ( ! $image ) {
	$image = '<span class="member-card-placeholder">' . esc_html__( 'Select a member image', 'devenci' ) . '</span>';
}

$label = $alt ? sprintf( __( 'View %s portfolio', 'devenci' ), $alt ) : __( 'View member portfolio', 'devenci' );
?>
<a class="member" href="<?php echo esc_url( $url ? $url : '#' ); ?>" style="--delay:<?php echo esc_attr( $delay ); ?>" aria-label="<?php echo esc_attr( $label ); ?>">
	<?php echo $image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_get_attachment_image(). ?>
	<div class="member-name"><?php echo $content; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Rendered inner blocks. ?></div>
</a>
